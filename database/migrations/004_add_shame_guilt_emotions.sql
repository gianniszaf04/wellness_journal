-- Ντροπη και Ενοχη (12 συναισθηματα, ιδια με το Python/labels.py), με τα μηνυματα τους. Ιδια με το seed.sql
INSERT INTO emotions (name, color, emoji, description) VALUES
('Ντροπή',       '#C77DFF', '😳', 'Αίσθημα έκθεσης ή ότι κάτι δεν πάει καλά με τον εαυτό.'),
('Ενοχή',        '#8D6E63', '😔', 'Αίσθημα ότι έκανες κάτι λάθος σε κάποιον ή σε κάτι.')
ON DUPLICATE KEY UPDATE
    color = VALUES(color),
    emoji = VALUES(emoji),
    description = VALUES(description);

INSERT INTO motivational_messages (target_emotion, message_text, intensity_level)
SELECT e.id, m.message_text, m.intensity_level
FROM (
    SELECT 'Ντροπή' AS emotion_name, 1 AS intensity_level, 'Όλοι έχουμε στιγμές που θα θέλαμε να ξεχάσουμε. Μια αμήχανη στιγμή δεν σε ορίζει.' AS message_text
    UNION ALL SELECT 'Ντροπή', 1, 'Σκέψου τι θα έλεγες σε έναν φίλο αν του συνέβαινε το ίδιο. Πες το και στον εαυτό σου.'
    UNION ALL SELECT 'Ντροπή', 2, 'Η ντροπή θέλει να κρυφτείς, αλλά συχνά μικραίνει όταν τη μοιράζεσαι με κάποιον που σε αποδέχεται.'
    UNION ALL SELECT 'Ντροπή', 2, 'Αυτό που έγινε είναι μια στιγμή, όχι ολόκληρος ο εαυτός σου. Δοκίμασε να το γράψεις με πιο ήπια λόγια.'
    UNION ALL SELECT 'Ντροπή', 3, 'Φαίνεται πως η ντροπή σε βαραίνει πολύ. Δεν αξίζεις να σε κρίνεις τόσο σκληρά. Αν σε πνίγει, μίλησε με κάποιον που εμπιστεύεσαι ή κάλεσε το 10306.'
    UNION ALL SELECT 'Ντροπή', 3, 'Όταν η ντροπή γίνεται πολύ έντονη, βοηθάει να μιλήσεις με έναν ειδικό. Η Γραμμή 10306 λειτουργεί όλο το 24ωρο.'
    UNION ALL SELECT 'Ενοχή', 1, 'Η ενοχή δείχνει ότι νοιάζεσαι. Σκέψου αν υπάρχει ένα μικρό βήμα για να το διορθώσεις.'
    UNION ALL SELECT 'Ενοχή', 1, 'Το ότι το σκέφτεσαι ήδη λέει πολλά για σένα. Δώσε στον εαυτό σου και λίγη κατανόηση.'
    UNION ALL SELECT 'Ενοχή', 2, 'Μια ειλικρινής συγγνώμη ή μια συζήτηση μπορεί να ελαφρύνει το βάρος. Τι θα ήταν εφικτό σήμερα;'
    UNION ALL SELECT 'Ενοχή', 2, 'Χώρισε τι ήταν στο χέρι σου και τι όχι. Δεν φέρεις την ευθύνη για όλα.'
    UNION ALL SELECT 'Ενοχή', 3, 'Η ενοχή σου φαίνεται πολύ βαριά. Όλοι κάνουμε λάθη και αξίζουμε συγχώρεση, και από τον εαυτό μας. Αν δεν σε αφήνει να ησυχάσεις, κάλεσε το 10306.'
    UNION ALL SELECT 'Ενοχή', 3, 'Όταν οι τύψεις δεν φεύγουν, αξίζει να τις συζητήσεις με κάποιον που εμπιστεύεσαι ή με έναν ειδικό. Δεν χρειάζεται να τις κουβαλάς μόνος ή μόνη σου.'
) AS m
JOIN emotions e ON e.name = m.emotion_name
WHERE NOT EXISTS (
    SELECT 1 FROM motivational_messages mm
    WHERE mm.target_emotion = e.id
      AND mm.message_text = m.message_text
);
